// Writes docs/MODEL_MANIFEST.md from models/registry.json and re-hashes every bundled file (mandate section 13 / acquisition + checksum report).
// node tools/model-manifest.js          -> prints the report and exits 1 if a bundled file does not match its recorded size/SHA-256
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const root = path.join(__dirname, '..'), reg = JSON.parse(fs.readFileSync(path.join(root, 'models/registry.json'), 'utf8')).models;
const rows = []; let bad = 0;
for (const [id, m] of Object.entries(reg)) {
  const files = m.files && m.files.length ? m.files : [{ file: '(bundled earlier, no hash listed)' }];
  for (const f of files) {
    const p = path.join(root, 'models', f.local || f.file || ''); let state = 'NOT BUNDLED';
    if (f.file && fs.existsSync(p)) {
      const size = fs.statSync(p).size, h = crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
      const okSize = !f.bytes || size === f.bytes, okHash = !f.sha256 || h === f.sha256;
      state = okSize && okHash ? (f.sha256 ? 'PASS (size+SHA-256)' : 'present, no recorded hash') : 'FAIL'; if (state === 'FAIL') bad++;
    }
    rows.push({ id, title: m.title, role: m.role, licence: m.licence, commercial: m.commercial, file: f.file, bytes: f.bytes || '', sha: f.sha256 || '', rev: m.revision ? m.revision.upstreamCommit.slice(0, 12) : '', state });
  }
}
const md = ['# Model manifest and checksum report (generated by tools/model-manifest.js)', '', '| id | role | licence | commercial | file | bytes | SHA-256 | upstream commit | local check |', '|---|---|---|---|---|---|---|---|---|']
  .concat(rows.map((r) => `| ${r.id} | ${r.role} | ${r.licence} | ${r.commercial} | ${r.file} | ${r.bytes} | ${r.sha ? r.sha.slice(0, 12) + '…' : ''} | ${r.rev} | ${r.state} |`)).join('\n') + '\n';
fs.writeFileSync(path.join(root, 'docs/MODEL_MANIFEST.md'), md); console.log(md); process.exit(bad ? 1 : 0);
